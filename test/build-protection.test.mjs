test('构建成功：替换 lib、清除陈旧文件、暂存目录在项目内', async (t) => {
  const root = await makeFixture(t);
  let stageDir;
  const result = await buildProject({
    root,
    lockWaitMs: 0,
    renameRetries: 0,
    log: () => {},
    stages: stubStages({
      compile: async (context) => {
        stageDir = context.stageDir;
        await writeStageFiles(context.stageDir, { tag: 'NEW' });
      },
    }),
  });
  assert.equal(dirname(stageDir), root, 'staging directory must live inside the project root (same volume)');
  assert.ok(resolve(stageDir).startsWith(resolve(root) + sep));
  assert.equal(result.files, KEY_FILES.length);
  assert.ok(result.bytes > 0);
  assert.equal(result.libDir, join(root, 'lib'));
  const files = await hashTree(join(root, 'lib'));
  for (const rel of KEY_FILES) assert.ok(files[rel], 'key file missing after publish: ' + rel);
  assert.equal(files['stale.js'], undefined, 'stale file must be gone after a full replacement');
  assert.equal(existsSync(join(root, 'lib', 'stale-dir')), false, 'stale directory must be gone');
  assert.equal(await readFile(join(root, 'lib', 'index.js'), 'utf8'), 'NEW index.js\n');
  assert.ok(
    (await readFile(join(root, 'lib', 'client.js'), 'utf8')).includes('window.__ModuleLoader__.load('),
    'published client bundle must keep its loader banner',
  );
  await assertClean(root);
});

test('已有构建持锁：立即失败、不改 lib、不删除他人的锁', async (t) => {
  const root = await makeFixture(t);
  const before = await snapshotLib(root);
  const lockPath = join(root, BUILD_LOCK);
  const foreign = JSON.stringify({ pid: process.pid, token: 'foreign-owner', startedAt: new Date().toISOString() });
  await writeFile(lockPath, foreign);
  await assert.rejects(
    buildProject({ root, lockWaitMs: 0, renameRetries: 0, log: () => {}, stages: stubStages() }),
    /another build is already running/,
  );
  assert.deepEqual(await snapshotLib(root), before);
  assert.equal(await readFile(lockPath, 'utf8'), foreign, 'a foreign lock must not be removed');
  await rm(lockPath);
  await assertClean(root);
});

test('死进程留下的锁会被回收，构建继续', async (t) => {
  const root = await makeFixture(t);
  const lockPath = join(root, BUILD_LOCK);
  await writeFile(
    lockPath,
    JSON.stringify({ pid: 424242, token: 'dead-owner', startedAt: new Date(0).toISOString() }),
  );
  const result = await buildProject({
    root,
    lockWaitMs: 0,
    renameRetries: 0,
    log: () => {},
    isPidAlive: () => false,
    stages: stubStages(),
  });
  assert.equal(result.files, KEY_FILES.length);
  await assertClean(root);
});

test('并发构建串行化：第二个构建等待第一个完成后成功', async (t) => {
  const root = await makeFixture(t);
  let releaseCompile;
  const gate = new Promise((resolveGate) => {
    releaseCompile = resolveGate;
  });
  let signalStarted;
  const started = new Promise((resolveStarted) => {
    signalStarted = resolveStarted;
  });
  const first = buildProject({
    root,
    lockWaitMs: 2000,
    renameRetries: 0,
    log: () => {},
    stages: stubStages({
      compile: async ({ stageDir }) => {
        signalStarted();
        await gate;
        await writeStageFiles(stageDir, { tag: 'FIRST' });
      },
    }),
  });
  await started;
  const second = buildProject({
    root,
    lockWaitMs: 10000,
    renameRetries: 0,
    log: () => {},
    stages: stubStages({
      compile: async ({ stageDir }) => writeStageFiles(stageDir, { tag: 'SECOND' }),
    }),
  });
  await new Promise((resolveDelay) => setTimeout(resolveDelay, 100));
  releaseCompile();
  const [firstResult, secondResult] = await Promise.all([first, second]);
  assert.equal(firstResult.files, KEY_FILES.length);
  assert.equal(secondResult.files, KEY_FILES.length);
  assert.equal(
    await readFile(join(root, 'lib', 'index.js'), 'utf8'),
    'SECOND index.js\n',
    'the waiting build must publish after the first one finishes',
  );
  await assertClean(root);
});

test('发布阶段失败会回滚旧 lib，并报告已恢复', async (t) => {
  const root = await makeFixture(t);
  const before = await snapshotLib(root);
  const calls = [];
  const rename = async (from, to) => {
    const source = relative(root, resolve(from)).split(sep).join('/');
    const target = relative(root, resolve(to)).split(sep).join('/');
    calls.push([source, target]);
    if (source.startsWith('.build-stage-') && target === 'lib') {
      const error = new Error('EPERM: simulated publish failure');
      error.code = 'EPERM';
      throw error;
    }
    return fsRename(from, to);
  };
  await assert.rejects(
    buildProject({
      root,
      lockWaitMs: 0,
      renameRetries: 0,
      rename,
      log: () => {},
      stages: stubStages(),
    }),
    /publish failed; previous lib restored from backup: EPERM: simulated publish failure/,
  );
  assert.deepEqual(await snapshotLib(root), before, 'rollback must restore the old lib byte-for-byte');
  const shape = calls.map(([from, to]) => [
    from === 'lib'
      ? 'lib'
      : from.startsWith('.build-stage-')
        ? 'stage'
        : from.startsWith('.build-backup-')
          ? 'backup'
          : from,
    to === 'lib' ? 'lib' : to.startsWith('.build-backup-') ? 'backup' : to,
  ]);
  assert.deepEqual(shape, [
    ['lib', 'backup'],
    ['stage', 'lib'],
    ['backup', 'lib'],
  ]);
  await assertClean(root);
});

test('上次替换中断（lib 缺失 + 备份存在）：先恢复备份再构建', async (t) => {
  const root = await makeFixture(t);
  const backup = join(root, '.build-backup-99999-dead');
  await fsRename(join(root, 'lib'), backup);
  const leftoverStage = join(root, '.build-stage-99999-old');
  await mkdir(leftoverStage, { recursive: true });
  await writeFile(join(leftoverStage, 'junk.js'), 'leftover\n');
  const result = await buildProject({
    root,
    lockWaitMs: 0,
    renameRetries: 0,
    log: () => {},
    stages: stubStages(),
  });
  assert.equal(result.files, KEY_FILES.length);
  const files = await hashTree(join(root, 'lib'));
  assert.equal(await readFile(join(root, 'lib', 'index.js'), 'utf8'), 'NEW index.js\n');
  assert.equal(files['stale.js'], undefined, 'the recovered old lib is replaced by the new build');
  await assertClean(root);
});
