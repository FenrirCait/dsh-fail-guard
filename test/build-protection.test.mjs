// dsh-fail-guard · 构建保护测试（隔离目录）
// 运行：node --test test/build-protection.test.mjs
//
// 每个用例在 os.tmpdir() 下搭一个独立假项目，构建只在假项目的 lib 上操作；
// 不读写仓库的 lib，不运行 npm test，不访问任何 profile。

import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { mkdir, mkdtemp, readFile, readdir, rename as fsRename, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { buildProject, BUILD_LOCK, KEY_FILES } from '../scripts/build.mjs';

const CLIENT_BUNDLE =
  '// Generated by npm run build.\n' +
  'window.__ModuleLoader__.load({ id: "dsh-fail-guard", factory: function (require) { return __guardClient; } });\n';

async function makeFixture(t) {
  const root = await mkdtemp(join(tmpdir(), 'dsh-fail-guard-build-'));
  t.after(async () => {
    await rm(root, { recursive: true, force: true });
  });
  await mkdir(join(root, 'src'), { recursive: true });
  await writeFile(join(root, 'src', 'index.ts'), 'export const fixture = true;\n');
  await mkdir(join(root, 'lib', 'failure'), { recursive: true });
  await mkdir(join(root, 'lib', 'repetition'), { recursive: true });
  await writeFile(join(root, 'lib', 'index.js'), 'OLD index.js\n');
  await writeFile(join(root, 'lib', 'index.d.ts'), 'OLD index.d.ts\n');
  await writeFile(join(root, 'lib', 'client.js'), 'OLD client.js\n');
  await writeFile(join(root, 'lib', 'failure', 'index.js'), 'OLD failure/index.js\n');
  await writeFile(join(root, 'lib', 'repetition', 'index.js'), 'OLD repetition/index.js\n');
  await writeFile(join(root, 'lib', 'stale.js'), 'STALE FILE must disappear after a successful build\n');
  await mkdir(join(root, 'lib', 'stale-dir'), { recursive: true });
  await writeFile(join(root, 'lib', 'stale-dir', 'old.js'), 'STALE DIR\n');
  return root;
}

async function hashTree(dir, base = dir, out = {}) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    const rel = relative(base, full).split(sep).join('/');
    if (entry.isDirectory()) await hashTree(full, base, out);
    else if (entry.isFile()) out[rel] = createHash('sha256').update(await readFile(full)).digest('hex');
  }
  return out;
}

const snapshotLib = (root) => hashTree(join(root, 'lib'));

async function writeStageFiles(stageDir, { tag = 'NEW', omit = [] } = {}) {
  for (const rel of KEY_FILES) {
    if (omit.includes(rel)) continue;
    const full = join(stageDir, rel);
    await mkdir(dirname(full), { recursive: true });
    await writeFile(full, rel === 'client.js' ? CLIENT_BUNDLE : tag + ' ' + rel + '\n');
  }
}

function stubStages(overrides = {}) {
  return {
    typecheck: async () => {},
    compile: async ({ stageDir }) => writeStageFiles(stageDir),
    bundle: async () => {},
    ...overrides,
  };
}

async function artifacts(root) {
  return (await readdir(root)).filter(
    (name) => name === BUILD_LOCK || name.startsWith('.build-stage-') || name.startsWith('.build-backup-'),
  );
}

async function assertClean(root) {
  assert.deepEqual(await artifacts(root), [], 'no lock/stage/backup should be left behind');
}

test('编译失败但已生成部分新文件：旧 lib 逐字节不变、无残留', async (t) => {
  const root = await makeFixture(t);
  const before = await snapshotLib(root);
  await assert.rejects(
    buildProject({
      root,
      lockWaitMs: 0,
      renameRetries: 0,
      log: () => {},
      stages: stubStages({
        compile: async ({ stageDir }) => {
          await mkdir(join(stageDir, 'failure'), { recursive: true });
          await writeFile(join(stageDir, 'index.js'), 'PARTIAL NEW index.js\n');
          await writeFile(join(stageDir, 'failure', 'index.js'), 'PARTIAL NEW failure\n');
          throw new Error('simulated tsc failure');
        },
      }),
    }),
    /build failed during compile: simulated tsc failure/,
  );
  assert.deepEqual(await snapshotLib(root), before, 'old lib must stay byte-identical');
  assert.equal(existsSync(join(root, 'lib', 'stale.js')), true, 'old stale file belongs to the old lib');
  await assertClean(root);
});

